import 'dart:math';

/// A random `client_secret` for the password reset by e-mail. It proves that
/// the person who clicks the link started the request, so it must not be
/// guessable (the old value was the clock).
String newClientSecret([Random? random]) {
  final source = random ?? Random.secure();
  return List.generate(
    16,
    (_) => source.nextInt(256).toRadixString(16).padLeft(2, '0'),
  ).join();
}
